/**
 * @file    sample_launcher.c
 * @brief   Sample launcher implementation — load config + select/dispatch samples (no main).
 *
 *   Samples and "how to select a sample" are orthogonal: every sample is *_run(ctx);
 *   this file only decides the front door. Three front doors (chosen at compile time
 *   via SAMPLE_AUTORUN*, mutually exclusive):
 *
 *     1) Interactive menu (default)   — single-char selection ('1'..'9' / 'q').
 *        MCU port = implement sample_console_getch() to read 1 byte.
 *     2) -DSAMPLE_AUTORUN_ALL    — no input needed: cycle through all samples on boot (with optional budget/loop).
 *     3) -DSAMPLE_AUTORUN="name" — no input needed: run only the specified sample on boot.
 *
 *   Direct / global commands are always available (under any front door, Linux/CI):
 *     sample_things_model <name> [args]   run a sample directly (args passed through, e.g. camera -v)
 *     sample_things_model --list          list all samples (script-friendly)
 *     sample_things_model --help          overall usage
 *   —— --list/--help/menu are all generated by iterating the registry; adding a sample is
 *      auto-collected with zero extra changes.
 *
 *   Cancellation: Ctrl-C while a sample runs (MCU: UART 'q' -> sample_request_stop()) ->
 *   sample_should_stop() is set -> sample finishes and returns -> back to menu / next one / end.
 *
 *   This file is platform-neutral library code: no main(); it is called by each platform's
 *   entry point (e.g. projects/linux/main.c, projects/rtos/gd32f527/app/launcher_task.c)
 *   via sample_launcher_run().
 */
#include "sample_registry.h"
#include "sample_launcher.h"
#include "sample_config.h"
#include "sample_lifecycle.h"
#include "thing_model_client/thing_model_client_osal.h"
#include "thing_model_client_log.h"
#include "sample_supervisor.h"         /* SampleSupervisor type is used by print_samples() in every front door (incl. autorun), not just the menu */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#if !defined(SAMPLE_AUTORUN) && !defined(SAMPLE_AUTORUN_ALL)
#  include "sample_console.h"          /* console adapter only needed in interactive menu mode */
#  include "sample_aircraft_info.h"    /* toggle aircraft-info subscription in the menu */
#  include "sample_session.h"          /* shared session opened once for the whole process */
#  if defined(__linux__) || defined(__unix__) || defined(__APPLE__)
#    include <unistd.h>                /* isatty: interactive shell vs headless (systemd) park */
#  endif
#endif

static bool entry_visible(const SampleEntry *e)
{
    return e && (!e->available || e->available());
}

/* autorun: is `name` present in THING_MODEL_DISABLED_SAMPLES (a comma/space-separated list)? Used to disable
 * (not run) a sample at run time. Whole-token match ("camera" won't hit "camera_x"). Empty list = all enabled. */
static bool name_in_disable_list(const char *list, const char *name)
{
    if (!list || !name) return false;
    size_t nlen = strlen(name);
    const char *p = list;
    while (*p) {
        while (*p == ',' || *p == ' ' || *p == '\t') p++;       /* skip separators */
        const char *start = p;
        while (*p && *p != ',' && *p != ' ' && *p != '\t') p++;  /* take one token */
        size_t tlen = (size_t)(p - start);
        if (tlen == nlen && strncmp(start, name, nlen) == 0) return true;
    }
    return false;
}

/* The only sample-list printer: iterates the registry — shared by menu / --list / --help.
 * Adding a sample only needs SAMPLE_REGISTER + one line in sample_list.inc; auto-collected here, no changes.
 * When sv != NULL (interactive menu), samples already resident as background services are skipped —
 * selecting them would only collide with the running instance; they are shown under 's' instead.
 * --list / --help pass sv = NULL so they still list every sample. */
static void print_samples(int numbered, const SampleSupervisor *sv)
{
    for (int i = 0; i < sample_registry_count(); ++i) {
        const SampleEntry *e = sample_registry_get(i);
        if (!entry_visible(e)) continue;
        if (sv && sample_supervisor_is_running(sv, e->name)) continue;  /* resident -> hide from the menu */
        if (numbered) printf("  %d) %-12s %s\n", i + 1, e->name, e->brief);
        else          printf("  %-12s %s\n", e->name, e->brief);
    }
}

static void print_usage(const char *prog)
{
    printf("Usage:\n"
           "  %s                          enter the interactive menu to select a sample\n"
           "  %s [global args] <name> [args]   run a sample directly (sample args passed through, e.g. camera -v)\n"
           "  %s --list                   list all samples\n"
           "  %s --help                   show this help\n"
           "  %s <name> -h                 view a sample's own args\n\n",
           prog, prog, prog, prog, prog);
    printf("Global args (must precede the sample name; apply uniformly to all samples, for multi-payload onboarding tests):\n"
           "  --sn <SN>,-s       onboarding device SN (= MQTT client_id, also the reported device_id)\n"
           "  --name <name>,-n   reported device name (device_info.device_name)\n"
           "  e.g.:  %s --sn payload_a --name pay_a upgrade   # works for any sample\n"
           "       %s --sn payload_b --name pay_b           # no sample name = enter menu, identity already set\n"
           "  (can also use env vars THING_MODEL_DEVICE_SN / THING_MODEL_DEVICE_NAME)\n\n",
           prog, prog);
    printf("Available samples:\n");
    print_samples(0, NULL);
}

/* Run a sample with default args (argv[0]=sample name), on the shared session when one is given
 * (shared may be NULL -> the sample opens its own, as in the zero-input autorun paths). */
static int run_entry(const SampleEntry *e, const ThingModelClientSession_Config_t *cfg,
                     ThingModelClientSession_t *shared)
{
    char     *av[1] = { (char *)e->name };
    SampleCtx ctx   = { .cfg = cfg, .session = shared, .argc = 1, .argv = av };
    sample_clear_stop();
    LOG_INFO("──── running sample: %s ────", e->name);
    int rc = e->run(&ctx);
    LOG_INFO("──── sample %s finished (rc=%d) ────", e->name, rc);
    return rc;
}

#if !defined(SAMPLE_AUTORUN) && !defined(SAMPLE_AUTORUN_ALL)
static void print_menu(const SampleSupervisor *sv)
{
    printf("\n==== Things-Model samples ====   [background services: %d running]\n",
           sample_supervisor_count(sv));
    print_samples(1, sv);            /* menu: hides resident services, so numbering may skip */
    printf("  a) aircraft-info subscription: %s (press a to toggle)\n",
           sample_aircraft_info_enabled() ? "on" : "off");
    printf("  s) show background services\n");
    printf("  q) quit    (Enter/m redraws this menu after logs scroll it off)\nselect> ");
    fflush(stdout);
}
#endif

int sample_launcher_run(int argc, char **argv)
{
    /* OSAL: auto-registered on POSIX platforms; on non-POSIX (MCU/RTOS) assumes the caller already registered its own OSAL. */
#if defined(__linux__) || defined(__unix__) || defined(__APPLE__)
    ThingModelOsal_RegisterPosix();
#endif
    /* Session config: loaded once for the whole process, shared by all samples. */
    ThingModelClientSession_Config_t cfg;
    thing_model_sample_config_load(&cfg);
    sample_lifecycle_install();

    /* ── Parse "prefix global args" (must precede the sample name): --list/--help global commands + --sn/--name
     *    common identity. The first token not starting with '-' is the sample name; everything after it is
     *    passed through verbatim to the sample (if the sample has same-named args — e.g. stress's --sn list,
     *    upgrade's --sn — they don't interfere). */
    const char *id_sn = NULL, *id_name = NULL;
    int ai = 1;
    for (; ai < argc && argv[ai][0] == '-'; ) {
        const char *a = argv[ai];
        if (!strcmp(a, "--list") || !strcmp(a, "-l")) { print_samples(0, NULL); return 0; }
        if (!strcmp(a, "--help") || !strcmp(a, "-h")) { print_usage(argv[0]); return 0; }
        if (!strcmp(a, "--sn")   || !strcmp(a, "-s")) {
            if (ai + 1 >= argc) { fprintf(stderr, "%s requires a value (device SN)\n", a); return 2; }
            id_sn = argv[++ai]; ai++; continue;
        }
        if (!strcmp(a, "--name") || !strcmp(a, "-n")) {
            if (ai + 1 >= argc) { fprintf(stderr, "%s requires a value (device name)\n", a); return 2; }
            id_name = argv[++ai]; ai++; continue;
        }
        fprintf(stderr, "unknown global option: %s (use --help for usage)\n", a);
        return 2;
    }

    /* Apply common identity: device_sn is written to both cfg and the environment (the latter for samples that
     * load config themselves, e.g. stress); the device name is passed via env var to the shared report module
     * (sample_device_report parses THING_MODEL_DEVICE_NAME). */
    if (id_sn) {
        cfg.device_sn = id_sn;
#if defined(__linux__) || defined(__unix__) || defined(__APPLE__)
        setenv("THING_MODEL_DEVICE_SN", id_sn, 1);
#endif
    }
#if defined(__linux__) || defined(__unix__) || defined(__APPLE__)
    if (id_name) setenv("THING_MODEL_DEVICE_NAME", id_name, 1);
#else
    (void)id_name;   /* non-POSIX: device name goes through a compile-time macro */
#endif

    /* Direct mode: ai points at the sample name (if any). The remaining args (from argv+ai) are passed through verbatim. */
    if (ai < argc) {
        const SampleEntry *e = sample_registry_find(argv[ai]);
        if (!e) {
            fprintf(stderr, "unknown sample: %s (use --list to see available items)\n", argv[ai]);
            return 2;
        }
        SampleCtx ctx = { .cfg = &cfg, .argc = argc - ai, .argv = argv + ai };
        sample_clear_stop();
        return e->run(&ctx);
    }
    /* No sample name given (maybe only --sn/--name) -> identity applied, fall through to the front door below (menu / autorun). */

#if defined(SAMPLE_AUTORUN_ALL)
    /* ── Front door 2: cycle through all samples, no input needed ──
     *   Each sample runs at most SAMPLE_AUTORUN_BUDGET seconds (0=no limit, relying on the sample to finish naturally);
     *   SAMPLE_AUTORUN_LOOP=1 loops the demo forever. */
#  ifndef SAMPLE_AUTORUN_BUDGET
#    define SAMPLE_AUTORUN_BUDGET 0
#  endif
#  ifndef SAMPLE_AUTORUN_LOOP
#    define SAMPLE_AUTORUN_LOOP 0
#  endif
    do {
        const char *disable_list = getenv("THING_MODEL_DISABLED_SAMPLES");   /* comma/space-separated sample names to disable (not run) at run time */
        for (int i = 0; i < sample_registry_count(); ++i) {
            const SampleEntry *e = sample_registry_get(i);
            if (!entry_visible(e)) continue;
            if (name_in_disable_list(disable_list, e->name)) {
                LOG_INFO("──── sample %s disabled (THING_MODEL_DISABLED_SAMPLES), not run ────", e->name);
                continue;
            }
            sample_deadline_arm(SAMPLE_AUTORUN_BUDGET);   /* auto-finish on deadline, advance to the next */
            run_entry(e, &cfg, NULL);
            sample_deadline_cancel();
        }
    } while (SAMPLE_AUTORUN_LOOP);
    LOG_INFO("autorun-all done.");
    return 0;

#elif defined(SAMPLE_AUTORUN)
    /* ── Front door 3: run only the compile-time-specified sample, no input needed ── */
    {
        const SampleEntry *e = sample_registry_find(SAMPLE_AUTORUN);
        if (!e) { fprintf(stderr, "the sample specified by SAMPLE_AUTORUN does not exist: %s\n", SAMPLE_AUTORUN); return 2; }
        return run_entry(e, &cfg, NULL);
    }

#else
    /* ── Default front door: one shared session + resident services + foreground shell ──
     *
     *   Collapses the former compile-time-exclusive branches (and the marker takeover) into one
     *   runtime flow:
     *     1) open the shared session ONCE (all samples run on it -> switching never reconnects);
     *     2) auto-start the configured background services (Linux: widget[+upgrade], see
     *        sample_autostart.inc) — resident and concurrent, on that same session;
     *     3) if a tty is attached, run the interactive shell; otherwise (systemd/CI, no tty) the
     *        services simply run and the process parks until SIGINT/SIGTERM. No marker files, no
     *        stdout redirection, no self-managed autostart — that is the init system's job. */
    {
        /* A payload is a resident service: the aircraft broker (or the network) is routinely not up
         * yet when we boot, and the runtime's Connect() only bounded-retries then returns NULL — the
         * unbounded reconnect worker takes over only AFTER a first success. So keep dialing here, with
         * backoff, until connected; Ctrl-C/SIGTERM breaks out cleanly. This is the single place that
         * owns "wait for the broker" (formerly duplicated inside the upgrade sample). */
        ThingModelClientSession_t *shared = NULL;
        for (unsigned attempt = 1; !sample_should_stop(); attempt++) {
            shared = sample_session_open(&cfg);
            if (shared) break;
            LOG_WARN("broker unreachable (attempt %u, broker=%s) — retrying in 5s, Ctrl-C to quit",
                     attempt, cfg.broker_address);
            for (int i = 0; i < 50 && !sample_should_stop(); i++) ThingModelOsal_SleepMs(100);
        }
        if (!shared) { printf("bye.\n"); return 0; }   /* stop requested before the broker came up */

        SampleSupervisor *sv = sample_supervisor_create(shared, &cfg);

        /* Auto-start services per policy (shared is guaranteed connected here). */
        if (sv) {
#  if defined(__linux__) || defined(__unix__) || defined(__APPLE__)
            /* The default policy runs the widget service, which owns the get_file_list handler. The
             * upgrade service embeds a fallback get_file_list responder (so an upgrade-only device is
             * still listed by DA2) — on the shared session that would double-answer. Disable it here;
             * overwrite=0 keeps an explicit user value, and an upgrade-only policy can set =1. */
            setenv("THING_MODEL_UPGRADE_WIDGET", "0", 0);
#  endif
#  define AUTOSTART(nm, eargc, eargv) do {                                          \
            int _rc = sample_supervisor_start(sv, #nm, (eargc), (eargv));            \
            if (_rc != 0) LOG_WARN("autostart %s failed (rc=%d)", #nm, _rc);         \
        } while (0);
#  if defined(__linux__) || defined(__unix__) || defined(__APPLE__)
#    include "sample_autostart.inc"
#  endif
#  undef AUTOSTART
        }

#  if defined(__linux__) || defined(__unix__) || defined(__APPLE__)
        int interactive = isatty(0);
#  else
        int interactive = 1;   /* MCU console is always "interactive" */
#  endif
        if (!interactive) {
            /* Headless: services run; park until a signal sets the foreground stop. */
            LOG_INFO("headless mode: %d background service(s) running; waiting for SIGINT/SIGTERM",
                     sample_supervisor_count(sv));
            while (!sample_should_stop()) ThingModelOsal_SleepMs(200);
        } else {
            /* Interactive menu, printed ON DEMAND rather than every iteration. The resident services
             * and the aircraft-info push keep logging at INFO (we deliberately keep the full log on
             * the console), and a menu reprinted on every keystroke would fight that stream — which
             * is exactly the "menu tangled with the logs" mess. So: print it once here (services are
             * already started above, so the running-count and the hiding of resident services are
             * accurate), redraw it after each action, and redraw on demand (Enter / m / ?) whenever
             * the log stream has scrolled it off screen. Logs simply flow in between. */
            print_menu(sv);
            for (;;) {
                int c = sample_console_getch();
                if (c < 0 || c == 'q' || c == 'Q') break;        /* exit */
                if (c == '\n' || c == '\r' || c == 'm' || c == 'M' || c == '?') {
                    print_menu(sv);                              /* redraw (menu scrolled off) */
                    continue;
                }
                if (c == 'a' || c == 'A') {                      /* toggle aircraft-info subscription */
                    bool on = !sample_aircraft_info_enabled();
                    sample_aircraft_info_set_enabled(on);
                    printf("aircraft-info subscription %s (takes effect immediately).\n",
                           on ? "enabled" : "disabled");
                    print_menu(sv);
                    continue;
                }
                if (c == 's' || c == 'S') {                      /* show background services */
                    printf("\n---- background services ----\n");
                    sample_supervisor_print(sv);
                    continue;
                }
                if (c < '1' || c > '9') { printf("invalid selection (press Enter to redraw the menu).\n"); continue; }

                const SampleEntry *e = sample_registry_get(c - '1');
                if (!entry_visible(e)) { printf("invalid selection (press Enter to redraw the menu).\n"); continue; }
                /* A service already resident in the background must not be started a second time
                 * (would collide on its HTTP port / duplicate its pushes). */
                if (sample_supervisor_is_running(sv, e->name)) {
                    printf("%s is already running as a background service (press s to view).\n", e->name);
                    continue;
                }
                run_entry(e, &cfg, shared);   /* runs on the shared session */
                print_menu(sv);               /* returned from the sample -> redraw the menu once */
            }
        }

        sample_supervisor_destroy(sv);        /* stop + join all services */
        sample_session_close(shared);
        printf("bye.\n");
        return 0;
    }
#endif
}

